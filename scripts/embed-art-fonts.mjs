// scripts/embed-art-fonts.mjs
//
// Embeds the poster's webfonts as base64 @font-face inside
// docs/artwork/ghost-riders-after-dark.svg, replacing the Google-Fonts
// @import. Why: SVG-as-<img> never fetches external resources, so every
// <img> surface (preview.html, side-by-side, vector-zoom) silently rendered
// the fallback fonts while a direct open of the file rendered Orbitron /
// Titan One — two different layouts from one file. data: URI fonts DO load
// in <img> SVGs, so embedding makes every surface render identically.
//
// Faces are exactly the ones the artwork uses (grep font-weight/font-family):
//   Orbitron 700 (.micro), Orbitron 900 (.display),
//   Space Grotesk 700 (.grot), Titan One 400 (Coalition wordmark)
// The previous @import also pulled Bebas Neue and Space Grotesk 500, which
// nothing references — they are dropped.
//
// Idempotent: re-running replaces the generated block between its markers.
// After changing the poster, rebuild the sticker sheet so its copied <defs>
// picks the faces up:  node scripts/build-sticker-sheet.mjs
//
// run: node scripts/embed-art-fonts.mjs   (needs network for fonts.gstatic.com)

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SVG = path.join(ROOT, 'docs', 'artwork', 'ghost-riders-after-dark.svg');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const REQUESTS = [
    { family: 'Orbitron', query: 'Orbitron:wght@700;900' },
    { family: 'Space Grotesk', query: 'Space+Grotesk:wght@700' },
    { family: 'Titan One', query: 'Titan+One' },
];

const BEGIN = '/* BEGIN EMBEDDED FONTS (generated by scripts/embed-art-fonts.mjs — do not edit by hand) */';
const END = '/* END EMBEDDED FONTS */';

async function latinFaces(query) {
    const cssUrl = `https://fonts.googleapis.com/css2?family=${query}&display=swap`;
    const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`css2 ${res.status} for ${query}`);
    const css = await res.text();
    const faces = [];
    const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([\s\S]*?)\}/g;
    let m;
    while ((m = re.exec(css))) {
        const [, subset, body] = m;
        if (subset !== 'latin') continue; // · (U+00B7) and all artwork text live in latin
        const weight = (body.match(/font-weight:\s*(\d+)/) || [])[1];
        const url = (body.match(/src:\s*url\((https:[^)]+\.woff2)\)/) || [])[1];
        const family = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
        if (!weight || !url || !family) throw new Error(`unparsable face in ${query}: ${body.slice(0, 120)}`);
        faces.push({ family, weight, url });
    }
    if (!faces.length) throw new Error(`no latin faces for ${query}`);
    return faces;
}

async function toDataUri(url) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`woff2 ${res.status} for ${url}`);
    const buf = Buffer.from(await res.arrayBuffer());
    return `data:font/woff2;base64,${buf.toString('base64')}`;
}

const faces = (await Promise.all(REQUESTS.map(r => latinFaces(r.query)))).flat();
const rules = [];
for (const f of faces) {
    const dataUri = await toDataUri(f.url);
    rules.push(`@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};src:url(${dataUri}) format('woff2')}`);
    console.log(`embedded ${f.family} ${f.weight} (${Math.round(dataUri.length / 1024)}KB base64)`);
}

const block = `${BEGIN}\n${rules.join('\n')}\n${END}`;

let svg = fs.readFileSync(SVG, 'utf8');
const before = svg.length;

if (svg.includes(BEGIN)) {
    const start = svg.indexOf(BEGIN);
    const end = svg.indexOf(END) + END.length;
    if (start < 0 || end < END.length) throw new Error('markers present but malformed');
    svg = svg.slice(0, start) + block + svg.slice(end);
} else {
    const importRe = /@import url\('https:\/\/fonts\.googleapis\.com[^']*'\);?\n?/;
    if (!importRe.test(svg)) throw new Error('no @import and no markers — unexpected style block');
    svg = svg.replace(importRe, block + '\n');
}

fs.writeFileSync(SVG, svg);
console.log(`svg ${Math.round(before / 1024)}KB -> ${Math.round(svg.length / 1024)}KB`);
