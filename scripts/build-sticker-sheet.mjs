// Builds docs/artwork/ghost-riders-stickers.svg — a print-ready kiss-cut
// sticker sheet (US Letter, 8.5x11in @ 300 DPI = 2550x3300) from the two
// vector wallet panels in docs/artwork/ghost-riders-after-dark.svg.
// Re-run after editing the artwork:  node scripts/build-sticker-sheet.mjs

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'docs', 'artwork', 'ghost-riders-after-dark.svg');
const OUT = path.join(ROOT, 'docs', 'artwork', 'ghost-riders-stickers.svg');

const src = fs.readFileSync(SRC, 'utf8');

// --- extract the reusable pieces from the poster ---

const defsOpen = src.indexOf('<defs>');
const defsClose = src.indexOf('</defs>');
if (defsOpen < 0 || defsClose < 0) throw new Error('no <defs> block in source');
const defs = src.slice(defsOpen, defsClose + '</defs>'.length);

// top panel art (skull gang): starts at the 400x288 panel rect,
// ends right before the seam-divider comment
const topStart = src.indexOf('<rect x="0" y="0" width="400" height="288"');
const seamIdx = src.indexOf('seam divider', topStart);
if (topStart < 0 || seamIdx < 0) throw new Error('top panel markers missing');
const topArt = src.slice(topStart, src.lastIndexOf('<!--', seamIdx));

// bottom panel art (banner): the translate(0 302) group,
// ends right before the blanket-stitch comment
const bottomStart = src.indexOf('<g transform="translate(0 302)">');
const stitchIdx = src.indexOf('blanket stitch edging', bottomStart);
if (bottomStart < 0 || stitchIdx < 0) throw new Error('bottom panel markers missing');
const bottomArt = src.slice(bottomStart, src.lastIndexOf('<!--', stitchIdx));

// --- sheet geometry (US Letter portrait @ 300 DPI) ---

const SHEET_W = 2550;
const SHEET_H = 3300;
const SCALE = 4.6;   // 400-wide panel -> 1840px sticker art
const BORDER = 32;   // white die-cut margin around each sticker
const CUT = 14;      // cut-guide offset outside the sticker

const ART1_W = Math.round(400 * SCALE);
const ART1_H = Math.round(288 * SCALE); // 1840 x 1325
const ART2_W = Math.round(400 * SCALE);
const ART2_H = Math.round(273 * SCALE); // 1840 x 1256

const outerW = ART => ART + 2 * BORDER;
const outerH = ART => ART + 2 * BORDER;

const S1 = { n: 1, x: (SHEET_W - outerW(ART1_W)) / 2, y: 190, artW: ART1_W, artH: ART1_H };
const S2 = { n: 2, x: (SHEET_W - outerW(ART2_W)) / 2, y: S1.y + outerH(ART1_H) + 150, artW: ART2_W, artH: ART2_H };

// sticker = dashed cut guide + white die-cut border + clipped panel art + dark edge
function sticker({ n, x, y, artW, artH }, inner) {
  return `
  <g transform="translate(${x} ${y})">
    <rect x="${-CUT}" y="${-CUT}" width="${artW + 2 * BORDER + 2 * CUT}" height="${artH + 2 * BORDER + 2 * CUT}" rx="70" fill="none" stroke="#c9c4ba" stroke-width="4" stroke-dasharray="16 12"/>
    <rect width="${artW + 2 * BORDER}" height="${artH + 2 * BORDER}" rx="56" fill="#ffffff" stroke="#e5e0d6" stroke-width="2"/>
    <g clip-path="url(#stickerClip${n})">
      <g transform="translate(${BORDER} ${BORDER}) scale(${SCALE})">${inner}</g>
    </g>
    <rect x="${BORDER}" y="${BORDER}" width="${artW}" height="${artH}" rx="26" fill="none" stroke="#10141c" stroke-width="6"/>
  </g>`;
}

const clip1 = `<clipPath id="stickerClip1"><rect x="${BORDER}" y="${BORDER}" width="${ART1_W}" height="${ART1_H}" rx="26"/></clipPath>`;
const clip2 = `<clipPath id="stickerClip2"><rect x="${BORDER}" y="${BORDER}" width="${ART2_W}" height="${ART2_H}" rx="26"/></clipPath>`;

// bottom art carries a translate(0 302) from the poster; cancel it out
const bottomInner = `<g transform="translate(0 -302)">${bottomArt}</g>`;

const sheet = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GHOST RIDERS: AFTER DARK — kiss-cut sticker sheet.
     US Letter portrait (8.5 x 11 in) at 300 DPI = 2550 x 3300 px.
     Cut along the dashed lines. Generated by scripts/build-sticker-sheet.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${SHEET_W}" height="${SHEET_H}" viewBox="0 0 ${SHEET_W} ${SHEET_H}">
  <title>GHOST RIDERS: AFTER DARK — vector wallet panel stickers</title>
${defs.replace('</defs>', `  ${clip1}\n  ${clip2}\n</defs>`)}
  <rect width="${SHEET_W}" height="${SHEET_H}" fill="#f6f2ea"/>
  <text x="${SHEET_W / 2}" y="118" text-anchor="middle" font-family="Arial, sans-serif" font-size="34" letter-spacing="8" fill="#9a948a">KISS-CUT STICKER SHEET · CUT ALONG THE DASHED LINES</text>
${sticker(S1, topArt)}
${sticker(S2, bottomInner)}
  <text x="${SHEET_W / 2}" y="${SHEET_H - 105}" text-anchor="middle" font-family="Arial, sans-serif" font-size="38" letter-spacing="6" fill="#9a948a">GHOST RIDERS: AFTER DARK · SGCOALITION.XYZ · 1 OF 1 · NO REPRINTS</text>
</svg>
`;

fs.writeFileSync(OUT, sheet);
console.log('sticker sheet written:', OUT, '(', sheet.length, 'bytes )');
console.log('  sticker 1 (skull gang):', ART1_W + 'x' + ART1_H, 'art at', S1.x + ',' + S1.y);
console.log('  sticker 2 (banner):    ', ART2_W + 'x' + ART2_H, 'art at', S2.x + ',' + S2.y);
